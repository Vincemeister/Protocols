// Generates src/components/ui/icons.generated.ts from the ICONS table in
// design-system/components/bundle.js, so the app draws exactly the icon
// outlines the design system shows (they are Lucide's, at the version the
// system was built with). Runs before `dev` and `build`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const bundle = readFileSync(resolve(root, "design-system/components/bundle.js"), "utf8");
const table = bundle.slice(bundle.indexOf("var ICONS = {"), bundle.indexOf("};", bundle.indexOf("var ICONS = {")));
const icons = [...table.matchAll(/^\s*'([a-z0-9-]+)':\s*'(.*)',?\s*$/gm)].map(([, name, svg]) => [name, svg]);
if (icons.length < 30) throw new Error(`Only ${icons.length} icons found in bundle.js; has its ICONS table changed shape?`);

const out = [
  "// Generated by scripts/build-icons.mjs from design-system/components/bundle.js. Do not edit.",
  "export const DS_ICONS = {",
  ...icons.map(([name, svg]) => `  ${JSON.stringify(name)}: ${JSON.stringify(svg)},`),
  "} as const;",
  "",
  "export type DsIconName = keyof typeof DS_ICONS;",
  "",
].join("\n");
writeFileSync(resolve(root, "src/components/ui/icons.generated.ts"), out);
console.log(`icons.generated.ts written (${icons.length} icons)`);
