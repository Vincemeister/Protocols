// Turns supabase/seed/demo-content.mjs into:
//   supabase/seed/demo.json  the same rows the app reads from Supabase; used
//                            when Supabase is not connected (local, CI)
//   supabase/seed/demo.sql   inserts for the Supabase project (run it in the
//                            SQL editor, or let Claude run it through the connector)
//   public/demo/covers/*.svg the placeholder list covers
import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { covers, follows, likes, profiles } from "../supabase/seed/demo-content.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

// Stable ids: the same content always gets the same uuid, so re-seeding updates rows in place.
const id = (key) => {
  const h = createHash("sha1").update(`favolist-demo:${key}`).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const slug = (name) => name.toLowerCase().replace(/&/g, "and").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const at = (day) => `${day}T03:00:00+00:00`;

const data = { profiles: [], lists: [], products: [], reviews: [], referral_codes: [], follow_counts: [], like_counts: [] };
const followRows = [];
const likeRows = [];
const productIdBySlug = {};

for (const p of profiles) {
  const profileId = id(p.username);
  data.profiles.push({
    id: profileId, username: p.username, display_name: p.display_name, avatar_url: null, bio: p.bio,
    about: p.about, links: p.links, is_public: true, created_at: at("2026-08-01"),
  });
  p.lists.forEach((l, li) => {
    const listId = id(`${p.username}/${slug(l.name)}`);
    data.lists.push({
      id: listId, owner_id: profileId, slug: slug(l.name), name: l.name, intro: l.intro ?? null,
      cover_url: `/demo/covers/${l.cover}.svg`, is_public: true, numbered: !!l.numbered, position: li,
      created_at: at("2026-08-01"), updated_at: at(l.updated),
    });
    l.products.forEach((pr, pi) => {
      const productId = id(`${p.username}/${slug(l.name)}/${slug(pr.name)}`);
      productIdBySlug[slug(pr.name)] = productId;
      data.products.push({
        id: productId, list_id: listId, owner_id: profileId, slug: slug(pr.name), name: pr.name, brand: pr.brand ?? null,
        image_url: null, source_url: pr.url ?? null, source_domain: pr.url ? new URL(pr.url).hostname.replace(/^www\./, "") : null,
        position: pi, created_at: at(pr.added),
      });
      data.reviews.push({ product_id: productId, body_text: pr.review, tidied: false, published_at: at(pr.added), updated_at: at(pr.added) });
      if (pr.code) data.referral_codes.push({ product_id: productId, code: pr.code.code, link: null, benefit_text: pr.code.benefit, status: "active" });
    });
  });
}
for (const [a, b] of follows) followRows.push({ follower_id: id(a), followee_id: id(b) });
for (const [a, s] of likes) likeRows.push({ user_id: id(a), product_id: productIdBySlug[s] });
for (const p of data.profiles) {
  data.follow_counts.push({
    profile_id: p.id,
    followers: followRows.filter((f) => f.followee_id === p.id).length,
    following: followRows.filter((f) => f.follower_id === p.id).length,
  });
}
for (const pr of data.products) {
  const n = likeRows.filter((l) => l.product_id === pr.id).length;
  if (n) data.like_counts.push({ product_id: pr.id, likes: n });
}

writeFileSync(resolve(root, "supabase/seed/demo.json"), JSON.stringify(data, null, 2) + "\n");

// --- SQL ---------------------------------------------------------------
const q = (v) => (v === null || v === undefined ? "null" : typeof v === "boolean" || typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const insert = (table, rows, conflict, cols = Object.keys(rows[0])) =>
  `insert into public.${table} (${cols.join(", ")}) values\n` +
  rows.map((r) => `  (${cols.map((c) => (c === "links" ? `${q(JSON.stringify(r[c]))}::jsonb` : q(r[c]))).join(", ")})`).join(",\n") +
  `\non conflict ${conflict};\n`;
const upsert = (cols, key) => `(${key}) do update set ${cols.filter((c) => !key.split(", ").includes(c)).map((c) => `${c} = excluded.${c}`).join(", ")}`;

const sql = [
  "-- Demo profiles (generated by scripts/build-seed.mjs from demo-content.mjs). Safe to run again.",
  "-- The follow and save triggers write notifications; that is fine for demo data.",
  insert("profiles", data.profiles, upsert(Object.keys(data.profiles[0]), "id")),
  insert("lists", data.lists, upsert(Object.keys(data.lists[0]), "id")),
  insert("products", data.products, upsert(Object.keys(data.products[0]), "id")),
  insert("reviews", data.reviews, upsert(Object.keys(data.reviews[0]), "product_id")),
  insert("referral_codes", data.referral_codes, upsert(Object.keys(data.referral_codes[0]), "product_id")),
  insert("follows", followRows, "do nothing"),
  insert("likes", likeRows, "do nothing"),
].join("\n");
writeFileSync(resolve(root, "supabase/seed/demo.sql"), sql);

mkdirSync(resolve(root, "public/demo/covers"), { recursive: true });
for (const [name, tone] of Object.entries(covers)) {
  writeFileSync(
    resolve(root, `public/demo/covers/${name}.svg`),
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 8 8" preserveAspectRatio="none"><rect width="8" height="8" fill="${tone}"/></svg>\n`,
  );
}
console.log(`demo seed: ${data.profiles.length} profiles, ${data.lists.length} lists, ${data.products.length} products`);
